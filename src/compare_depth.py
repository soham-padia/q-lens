"""D1 depth test across models -> results/tables/depth_test.md (CPU, reads <W>/<dir>/D1.json, W = $QLENS_OUT).

Question: is the early-layer first-order miss an accumulation over layers traversed (same per-layer nonlinearity in
every model, deeper models just traverse more), or a property of where the source sits (relative depth)?
Tables use alpha index A (default 0.2 rho) and the median over contexts x directions already stored in D1.json.
"""
import json
import os
import sys
from pathlib import Path

W = Path(os.environ.get("QLENS_OUT", "outputs"))
MODELS = [("Qwen3-8B", "so_qwen3-8b"), ("Qwen3-14B", "so_qwen3-14b"), ("Qwen3-32B", "so_qwen3-32b"),
          ("Qwen3.8-27B", "second_order_v1")]
A = float(sys.argv[1]) if len(sys.argv) > 1 else 0.2
OUT = Path(__file__).resolve().parent.parent / "results" / "tables" / "depth_test.md"

D = {}
for name, d in MODELS:
    p = W / d / "D1.json"
    if p.exists():
        D[name] = json.loads(p.read_text())
if not D:
    sys.exit("no D1.json yet")
md = [f"# D1 depth test (generated by src/compare_depth.py, alpha = {A} rho)", "",
      "Steer h_l at every valid position by alpha*rho*unit(dir); response at block l+k. rel_lin = |act - J d|/|act| "
      "(median over contexts x directions); rel_quad with J + Q/2. k is the absolute number of blocks traversed. "
      "`fin` = the final block.", ""]


def val(row, key, ai):
    v = row.get(key)
    return None if v is None else v[ai]


def fmt(x):
    return "—" if x is None else f"{x:.3f}"


for tn in ("iso", "data", "lens"):
    for key in ("rel_lin", "rel_quad"):
        md += [f"## {key}, {tn} directions: by source (nominal-64 depth) x k", ""]
        for name, d in D.items():
            ai = d["alphas"].index(A)
            ks = d["ks"] + ["fin"]
            md += [f"**{name}** ({d['n_layers']} layers)", "", "| source (nominal) | " + " | ".join(f"k={k}" for k in ks) + " |",
                   "|---" * (len(ks) + 1) + "|"]
            for l, v in sorted(d["sources"].items(), key=lambda kv: int(kv[0])):
                sm = v["summary"].get(tn)
                if sm is None:
                    continue
                byk = {r["k"]: r for r in sm.values()}
                fin = sm[str(d["n_layers"] - 1)] if str(d["n_layers"] - 1) in sm else None
                cells = [fmt(val(byk[k], key, ai)) if k in byk and int(l) + k < d["n_layers"] - 1 else "—" for k in d["ks"]]
                cells.append(fmt(val(fin, key, ai)) if fin else "—")
                md.append(f"| L{l} ({v['nominal']}) | " + " | ".join(cells) + " |")
            md.append("")

# the decisive view: per absolute k, median over sources, per model (iso and data)
for tn in ("iso", "data"):
    md += [f"## Per layer traversed: rel_lin at k (median over sources), {tn}", "",
           "| k | " + " | ".join(D) + " |", "|---" * (len(D) + 1) + "|"]
    allk = sorted({k for d in D.values() for k in d["ks"]})
    for k in allk:
        row = []
        for name, d in D.items():
            ai = d["alphas"].index(A)
            xs = sorted(r["rel_lin"][ai] for v in d["sources"].values() if tn in v["summary"]
                        for r in v["summary"][tn].values() if r["k"] == k)
            row.append(fmt(xs[len(xs) // 2]) if xs else "—")
        md.append(f"| {k} | " + " | ".join(row) + " |")
    md.append("")

md += ["## Q/J norm ratio at the final block (curvature size, alpha = 1), iso", "",
       "| model | " + " | ".join(f"src nominal {n}" for n in (8, 16, 24, 32, 40, 48, 56)) + " |", "|---" * 8 + "|"]
for name, d in D.items():
    byn = {v["nominal"]: v for v in d["sources"].values()}
    cells = []
    for n in (8, 16, 24, 32, 40, 48, 56):
        v = min(byn.items(), key=lambda kv: abs(kv[0] - n))[1] if byn else None
        fin = v["summary"]["iso"].get(str(d["n_layers"] - 1)) if v else None
        cells.append(fmt(fin["Q_over_J"]) if fin else "—")
    md.append(f"| {name} | " + " | ".join(cells) + " |")
md.append("")
OUT.write_text("\n".join(md))
print(f"wrote {OUT} ({len(D)} models: {list(D)})")
