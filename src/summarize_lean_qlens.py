def cboot_rates(cl, cols, B=1000, seed=0):
    """Pooled rates (mean of 0/1 columns over rows) with a cluster bootstrap over contexts; cols: {name: array}."""
    cl = np.asarray(cl)
    u, inv = np.unique(cl, return_inverse=True)
    rng = np.random.default_rng(seed)
    CNT = np.stack([np.bincount(rng.integers(0, len(u), len(u)), minlength=len(u)) for _ in range(B)])
    n_c = np.bincount(inv, minlength=len(u)).astype(float)
    out = {}
    for k, v in cols.items():
        v = np.asarray(v, float)
        s_c = np.bincount(inv, weights=v, minlength=len(u))
        br = (CNT @ s_c) / (CNT @ n_c)
        lo, hi = np.percentile(br, [2.5, 97.5])
        out[k] = (float(v.mean()), float(lo), float(hi))
    return out


