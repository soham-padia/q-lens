def cboot(stat, items, B=2000, seed=0):
    """Cluster bootstrap over contexts: items = list of (ci, value-tuple); stat(list of value-tuples)."""
    rng = np.random.default_rng(seed)
    by = {}
    for c, v in items:
        by.setdefault(c, []).append(v)
    keys = sorted(by)
    pt = stat([v for c in keys for v in by[c]])
    bs = []
    for _ in range(B):
        pick = rng.integers(0, len(keys), len(keys))
        bs.append(stat([v for i in pick for v in by[keys[i]]]))
    bs = [b for b in bs if b == b]
    lo, hi = np.percentile(bs, [2.5, 97.5]) if bs else (float("nan"), float("nan"))
    return float(pt), float(lo), float(hi)


def med(xs):
    return float(np.median(xs)) if len(xs) else float("nan")


def gates_e2(cases, layers, G2=None):
    """Original small-step gate; with gate2 output (Amendment 2) the FD part of the verdict comes from gate2."""
    out = {}
    for l in layers:
        fd = [c["L"][l]["fd"] for c in cases if "fd" in c["L"].get(l, {})]
        ex = [abs(c["L"][l]["g_tail1"] - c["g_full"]) / max(abs(c["g_full"]), 1e-12) for c in cases if l in c["L"]]
        g1, g2 = med([x["rel_g1"] for x in fd]), med([x["rel_g2"] for x in fd])
        out[l] = {"fd_rel_g1": g1, "fd_rel_g2": g2, "exact": med(ex), "n_fd": len(fd),
                  "pass_orig": bool(fd) and g1 < 0.05 and g2 < 0.05 and med(ex) < 1e-3}
        if G2 is not None:
            x = G2["E2"][l]
            out[l].update({"g2_rel_g1": x["med_rel_g1"], "g2_rel_g2": x["med_rel_g2"], "g2_n": x["n"],
                           "g2_max_g0_diff": x["max_g0_diff"], "pass": bool(x["pass"]) and med(ex) < 1e-3})
        else:
            out[l]["pass"] = out[l]["pass_orig"]
    return out


def gates_e3(pairs, layers, G2=None):
    out = {}
    for l in layers:
        fd = [max(v for s, v in p["L"][l]["cos_s"].items() if float(s) < 0.05) for p in pairs
              if l in p["L"] and any(float(s) < 0.05 for s in p["L"][l]["cos_s"])]
        out[l] = {"fd_best_cos": med(fd), "n_fd": len(fd), "pass_orig": bool(fd) and med(fd) > 0.99}
        if G2 is not None:
            x = G2["E3"][l]
            out[l].update({"g2_best_cos": x["med_best_cos"], "g2_n": x["n"], "g2_max_cos_diff": x["max_cos_diff"],
                           "pass": bool(x["pass"])})
        else:
            out[l]["pass"] = out[l]["pass_orig"]
    return out


def gate_lines(name, cor, g, kind):
    for l, x in g.items():
        if kind == "E2":
            t = (f"orig (eps 1e-2..1e-3, first {x['n_fd']}): rel g1 {f3(x['fd_rel_g1'])}, rel g2 {f3(x['fd_rel_g2'])}; "
                 f"exactness {x['exact']:.1e}")
            if "g2_n" in x:
                t += (f"; gate2 (eps .2..05 + Richardson, n={x['g2_n']}): rel g1 {f3(x['g2_rel_g1'])}, rel g2 "
                      f"{f3(x['g2_rel_g2'])}, max g0 recompute diff {x['g2_max_g0_diff']:.1e}")
        else:
            t = f"orig (s .03..003, first {x['n_fd']}): best cos {f3(x['fd_best_cos'])}"
            if "g2_n" in x:
                t += (f"; gate2 (symmetric s .3..05 + Richardson, n={x['g2_n']}): best cos {f3(x['g2_best_cos'])}, "
                      f"max cos recompute diff {x['g2_max_cos_diff']:.1e}")
        say(f"- {kind} gate {name} {cor} L{l}: {t} -> {'PASS' if x['pass'] else 'FAIL'}")


def e2_errors(cases, layers):
    """[(ci, layer, e_J, e_JQ, lam*, lam_J, lam_JQ)] over finite-lam* cases."""
    rows = []
    for c in cases:
        for l in layers:
            r = c["L"].get(l)
            if not r or not math.isfinite(r["lam_star"]):
                continue
            ls = r["lam_star"]
            eJ = abs(math.log(r["lam_J"] / ls)) if math.isfinite(r["lam_J"]) else math.inf
            eQ = abs(math.log(r["lam_JQ"] / ls)) if math.isfinite(r["lam_JQ"]) else math.inf
            rows.append((c["ci"], l, eJ, eQ, ls, r["lam_J"], r["lam_JQ"], c["cls"], r["r_edit"], c["cand"]))
    return rows


def calibrated(rows, layers, col, k=5):
    """|log(c_l lam_pred / lam*)| with c_l = exp(median log(lam*/lam_pred)) fitted on the other 4 context-folds."""
    out = []
    for i, r in enumerate(rows):
        f = r[0] % k
        tr = [math.log(x[4] / x[col]) for x in rows if x[0] % k != f and x[1] == r[1] and math.isfinite(x[col])]
        c = math.exp(np.median(tr)) if tr else 1.0
        out.append(abs(math.log(c * r[col] / r[4])) if math.isfinite(r[col]) else math.inf)
    return out


def gstr(g, layers):
    return ",".join(f"{l}({int(g[l]['pass'])})" for l in layers)


def verdict3(pt, lo, hi, n, nmin=30):
    if n < nmin:
        return "INCONCLUSIVE (underpowered)"
    if lo > 0:
        return "PASS"
    if pt <= 0 or hi <= 0:
        return "FAIL"
    return "INCONCLUSIVE"


