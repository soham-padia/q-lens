def e1_load(tag, corpus):
    p = W / tag / f"E1_{corpus}.pt"
    if not p.exists():
        return None
    d = torch.load(p, weights_only=False)
    meta, raw = d["meta"], d["raw"]
    out = {}
    for tn in ("iso", "data"):
        ks, ps, gs = [], [], []
        for s in sorted(raw):
            R, tg = raw[s][tn], raw[s]["targets"]
            qj = (R["norm_Q"] / R["norm_J"]).double().numpy()
            for ti, t in enumerate(tg):
                ks.append(t - s); ps.append(s); gs.append(qj[:, :, ti])
        out[tn] = (np.array(ks, float), np.array(ps), np.stack(gs, -1))
    out["rho"] = {int(k): v for k, v in meta["rho"].items()}
    out["n_layers"] = meta["n_layers"]
    return out


def y_of(g):
    return np.log(np.median(g.reshape(-1, g.shape[-1]), 0))


def e1_stats(ks, ps):
    sv = sorted(set(ps.tolist()))
    Dm = np.stack([(ps == u).astype(float) for u in sv], 1)
    lk = np.log(ks)
    return {
        "level": lambda g: float(np.mean(y_of(g))),
        "slope": lambda g: float(np.polyfit(ks, y_of(g), 1)[0]),
        "within": lambda g: float(np.linalg.lstsq(np.c_[Dm, ks], y_of(g), rcond=None)[0][-1]),
        "power": lambda g: float(np.linalg.lstsq(np.c_[Dm, lk], y_of(g), rcond=None)[0][-1]),
    }


def boot(stat, terms, B=1000, seed=0):
    """terms: [(sign, G [C, D, P], corpus key)]; contexts resampled per corpus key (shared across terms with the same
    key, i.e. paired across models), direction indices shared by all terms (the paper's paired bootstrap)."""
    rng = np.random.default_rng(seed)
    pt = sum(s * stat(G) for s, G, _ in terms)
    nC = {k: G.shape[0] for _, G, k in terms}
    D = terms[0][1].shape[1]
    bs = []
    for _ in range(B):
        cix = {k: rng.integers(0, n, n) for k, n in nC.items()}
        di = rng.integers(0, D, D)
        bs.append(sum(s * stat(G[cix[k]][:, di]) for s, G, k in terms))
    lo, hi = np.nanpercentile(bs, [2.5, 97.5])
    return float(pt), float(lo), float(hi)


def rescaled(E, ref):
    """r at a matched absolute push: r * rho_ref,l / rho_corpus,l (r is exactly linear in the push size)."""
    out = {}
    for tn in ("iso", "data"):
        ks, ps, G = E[tn]
        fac = np.array([ref["rho"][int(p)] / E["rho"][int(p)] for p in ps])
        out[tn] = (ks, ps, G * fac)
    return out


